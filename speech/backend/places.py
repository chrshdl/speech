"""
The places the weather can be asked for by name, such as "what's the
weather in hamburg", with their coordinates.

places.tsv lists them, generated from GeoNames (https://www.geonames.org,
CC BY 4.0) by running this module on its cities15000.zip:

    curl -LO https://download.geonames.org/export/dump/cities15000.zip
    uv run python -m speech.backend.places cities15000.zip

It keeps the towns of Germany, Austria and Switzerland with 50,000 people
or more, the world's capitals and its cities of 3 million or more.
"""

import argparse
import csv
import dataclasses
import io
import os
import re
import unicodedata
import zipfile

PLACES_FILE = os.path.join(os.path.dirname(__file__), "places.tsv")

# Countries whose towns are kept down to MIN_TOWN people, the others only
# down to MIN_CITY, and capitals always.
HOME_COUNTRIES = {"DE", "AT", "CH"}
MIN_TOWN = 50_000
MIN_CITY = 3_000_000

# Other names people say for some places, by GeoNames name.
ALIASES = {
    "Munich": ["muenchen", "munchen"],
    "Köln": ["cologne"],
    "Nuremberg": ["nurnberg", "nuernberg"],
    "Vienna": ["wien"],
    "Zürich": ["zurich"],
    "Geneva": ["genf"],
    "Rome": ["rom"],
    "Prague": ["prag"],
    "Copenhagen": ["kopenhagen"],
    "New York City": ["new york"],
}

# Parts of German town names that people leave out, such as "Frankfurt am
# Main" said as "frankfurt".
SUFFIX = re.compile(r"\s+(am|an der|im|in der|ob der|bei)\s.*$")


@dataclasses.dataclass(frozen=True)
class Place:
    name: str
    country: str
    latitude: float
    longitude: float
    population: int


def spoken(name):
    """
    A name in the characters of the speech models: lowercase letters,
    the apostrophe and spaces. Returns None if nothing is left.
    """
    name = unicodedata.normalize("NFKD", name)
    name = "".join(c for c in name if not unicodedata.combining(c)).lower()
    name = re.sub(r"\(.*?\)", " ", name)
    name = re.sub(r"[^a-z' ]", " ", name)
    name = " ".join(name.split())
    return name or None


def spoken_forms(name, asciiname):
    forms = {spoken(name), spoken(asciiname)} - {None}
    forms |= {SUFFIX.sub("", form) for form in forms}
    forms.update(ALIASES.get(name, []))
    return sorted(f for f in forms if f)


def load(path=PLACES_FILE):
    """Returns a dict from each spoken form of a place to the Place."""
    places = {}
    with open(path, newline="", encoding="utf-8") as fid:
        for row in csv.DictReader(
            (l for l in fid if not l.startswith("#")), delimiter="\t"
        ):
            places[row["spoken"]] = Place(
                row["name"],
                row["country"],
                float(row["latitude"]),
                float(row["longitude"]),
                int(row["population"]),
            )
    return places


def generate(zip_path, out_path=PLACES_FILE):
    """Writes places.tsv from GeoNames' cities15000.zip."""
    with zipfile.ZipFile(zip_path) as archive:
        text = io.TextIOWrapper(archive.open("cities15000.txt"), encoding="utf-8")
        rows = list(csv.reader(text, delimiter="\t", quoting=csv.QUOTE_NONE))
    # Of places said the same way, the one with the most people.
    places = {}
    for row in rows:
        name, asciiname, lat, lon, code, country, population = (
            row[1],
            row[2],
            row[4],
            row[5],
            row[7],
            row[8],
            int(row[14] or 0),
        )
        keep = (
            code == "PPLC"
            or population >= MIN_CITY
            or (country in HOME_COUNTRIES and population >= MIN_TOWN)
        )
        if not keep:
            continue
        for form in spoken_forms(name, asciiname):
            if form not in places or population > places[form][4]:
                places[form] = (name, country, lat, lon, population)
    with open(out_path, "w", newline="", encoding="utf-8") as fid:
        fid.write(
            "# Generated by speech/backend/places.py from GeoNames "
            "(https://www.geonames.org), CC BY 4.0.\n"
        )
        writer = csv.writer(fid, delimiter="\t", lineterminator="\n")
        writer.writerow(
            ["spoken", "name", "country", "latitude", "longitude", "population"]
        )
        for form in sorted(places):
            writer.writerow([form, *places[form]])
    return len(places)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate places.tsv from GeoNames.")
    parser.add_argument("zip", help="GeoNames' cities15000.zip.")
    args = parser.parse_args()
    print(f"Wrote {generate(args.zip)} spoken names to {PLACES_FILE}")
